#!/bin/sh
# Writes Sources/OverSireAI/Prompts/PromptFiles.swift from Contract/prompts/*.md.
# The app has no resource bundle, so the files go into the binary as Swift text.
set -e
cd "$(dirname "$0")/.."
out=Sources/OverSireAI/Prompts/PromptFiles.swift
{
  echo '// Generated by scripts/gen-prompts.sh from Contract/prompts. Do not edit.'
  echo
  echo 'enum PromptFiles {'
  echo '    static let all: [String: String] = ['
  for f in Contract/prompts/*.md; do
    n=$(basename "$f" .md)
    [ "$n" = README ] && continue
    printf '        "%s": #"""\n' "$n"
    cat "$f"
    printf '\n"""#,\n'
  done
  echo '    ]'
  echo '}'
} > "$out"
echo "Wrote $out"
